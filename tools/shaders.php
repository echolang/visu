#!/usr/bin/env php
<?php

/**
 * Compile Vulkan GLSL to SPIR-V and Metal.
 *
 *   php tools/shaders.php
 *   php tools/shaders.php examples/shader/shaders
 *   php tools/shaders.php --check
 *   php tools/shaders.php --bake
 *   php tools/shaders.php --include /path/to/resources/shaders/include
 *
 * Library GLSL lives in `resources/shaders/` (`blit/`, `vg/`, `ui/`,
 * `include/visu`). `--bake` writes the Echo byte files in src/.
 * Source is `quad.vert` / `quad.frag` (glslang stage files).
 * Outputs are `quad.vert.spv` + `quad.vert.metal`, plus
 * `name+variant.*` for `#pragma visu variant` and a
 * `shaders.manifest` per tree.
 */

const MARKER = '// generated by tools/shaders.php — do not edit';
const MTL_UNIFORM_BASE = 2;
const UNIFORM_SLOTS = 4;
const TEXTURE_SLOTS = 16;
const PREAMBLE = '#extension GL_GOOGLE_include_directive : enable';
const VARIANT_PRAGMA = '/^\s*#pragma\s+visu\s+variant\s+(\S+)(.*)$/m';

const STAGES = [
    'vert' => ['glslang' => 'vert', 'spirv' => 'vert', 'entry' => 'vs'],
    'frag' => ['glslang' => 'frag', 'spirv' => 'frag', 'entry' => 'fs'],
    'geo' => ['glslang' => 'geom', 'spirv' => 'geom', 'entry' => ''],
    'tessc' => ['glslang' => 'tesc', 'spirv' => 'tesc', 'entry' => ''],
    'tesse' => ['glslang' => 'tese', 'spirv' => 'tese', 'entry' => 'vs'],
    'comp' => ['glslang' => 'comp', 'spirv' => 'comp', 'entry' => 'cs'],
];

/**
 * Library shader trees baked into the module. Each is compiled like any
 * other tree (variants included) and emitted as one Echo file exposing
 * `<prefix>Bytes($program, ShaderKind) : string?`.
 */
const BAKES = [
    [
        'dir' => 'blit',
        'out' => 'src/graphics/renderer/blitshader.eco',
        'ns' => 'visu::graphics',
        'prefix' => 'blit',
        'title' => 'Baked fullscreen blit shaders.',
    ],
    [
        'dir' => 'vg',
        'out' => 'src/vg/vgshader.eco',
        'ns' => 'visu::vg',
        'prefix' => 'vg',
        'title' => 'Baked vector-graphics shaders.',
    ],
    [
        'dir' => 'pbr',
        'out' => 'src/graphics/deferred/pbrshader.eco',
        'ns' => 'visu::graphics',
        'prefix' => 'pbr',
        'title' => 'Baked deferred PBR shaders.',
    ],
    [
        'dir' => 'ui',
        'out' => 'src/ui/uishader.eco',
        'ns' => 'visu::ui',
        'prefix' => 'ui',
        'title' => 'Baked FlyUI shaders.',
    ],
];

const DEFAULT_TREES = [
    'resources/shaders',
    'examples/shader/shaders',
    'examples/quickstart/resources/shader',
    'examples/fullapp/resources/shader',
    'tests/resources/shaders',
];

function main(array $argv) : int
{
    $root = dirname(__DIR__);
    $args = array_slice($argv, 1);
    $check = false;
    $bake = false;
    $dirs = [];
    $includes = [];

    $n = count($args);
    for ($i = 0; $i < $n; $i++) {
        $arg = $args[$i];

        if ($arg === '--check') {
            $check = true;
            continue;
        }

        if ($arg === '--bake') {
            $bake = true;
            continue;
        }

        if ($arg === '--help' || $arg === '-h') {
            fwrite(STDOUT, usage());
            return 0;
        }

        if ($arg === '--include') {
            if ($i + 1 >= $n) {
                fwrite(STDERR, "shaders: --include needs a path\n");
                return 1;
            }
            $i++;
            $includes[] = $args[$i];
            continue;
        }

        if (str_starts_with($arg, '--include=')) {
            $includes[] = substr($arg, strlen('--include='));
            continue;
        }

        $dirs[] = $arg;
    }

    $defaultInclude = $root . DIRECTORY_SEPARATOR . 'resources' . DIRECTORY_SEPARATOR . 'shaders' . DIRECTORY_SEPARATOR . 'include';
    if (is_dir($defaultInclude)) {
        array_unshift($includes, $defaultInclude);
    }
    $includes = array_values(array_unique($includes));

    $glslang = findBin(['glslangValidator', 'glslang']);
    $spirvCross = findBin(['spirv-cross']);
    $spirvVal = findBin(['spirv-val']);

    if ($glslang === null) {
        fwrite(STDERR, "shaders: glslangValidator not found. brew install glslang\n");
        return 1;
    }

    if ($spirvCross === null) {
        fwrite(STDERR, "shaders: spirv-cross not found. brew install spirv-cross\n");
        return 1;
    }

    $tools = [
        'glslang' => $glslang,
        'spirvCross' => $spirvCross,
        'spirvVal' => $spirvVal,
        'includes' => $includes,
        'check' => $check,
    ];

    $failed = 0;
    $wrote = 0;

    // --check verifies the baked files too, so CI catches a stale bake
    if ($bake || $check) {
        foreach (BAKES as $spec) {
            $bakeResult = bakeTree($root, $spec, $tools);
            if ($bakeResult === 'error') {
                return 1;
            }
            if ($bakeResult === 'wrote') {
                $wrote = $wrote + 1;
            }
        }
    }

    if (empty($dirs)) {
        foreach (DEFAULT_TREES as $rel) {
            $dirs[] = $root . DIRECTORY_SEPARATOR . $rel;
        }
    }

    foreach ($dirs as $dir) {
        $abs = realpath($dir);

        if ($abs === false || !is_dir($abs)) {
            fwrite(STDERR, "shaders: not a directory: {$dir}\n");
            $failed = $failed + 1;
            continue;
        }

        $result = compileTree($abs, $tools);
        if ($result === 'error') {
            $failed = $failed + 1;
            continue;
        }
        if ($result === 'wrote') {
            $wrote = $wrote + 1;
        }
    }

    if ($failed > 0) {
        return 1;
    }

    if ($check) {
        fwrite(STDOUT, "shaders: generated files match\n");
        return 0;
    }

    fwrite(STDOUT, "shaders: wrote {$wrote} tree(s)\n");
    return 0;
}

function usage() : string
{
    return <<<TXT
Compile Vulkan GLSL to SPIR-V and Metal.

  php tools/shaders.php [dir...] [--check] [--bake] [--include dir]

With no dirs, compiles the library, example, and test shader trees.
--check compiles and diffs against the committed outputs.
--bake writes one Echo file per tree in BAKES (blit, vg, ui) from resources/shaders.
--include adds an extra -I directory (resources/shaders/include is default).

TXT;
}

function compileTree(string $tree, array $tools) : string
{
    $sources = collect($tree);

    if (empty($sources)) {
        fwrite(STDOUT, "shaders: no stage files in {$tree}\n");
        return 'same';
    }

    $programs = groupPrograms($sources);
    $failed = false;
    $wrote = false;
    $manifestLines = [];
    $expectedVariantOutputs = [];

    foreach ($programs as $stem => $stages) {
        $variants = unionVariants($stages);

        foreach ($stages as $src) {
            $result = compileStage($src, $tree, $tools, '', []);
            if ($result === 'error') {
                $failed = true;
                continue;
            }
            if ($result === 'wrote') {
                $wrote = true;
            }
        }

        foreach ($variants as $variant => $defines) {
            $manifestLines[] = manifestLine($stem, $variant, $defines);

            foreach ($stages as $src) {
                $result = compileStage($src, $tree, $tools, $variant, $defines);
                if ($result === 'error') {
                    $failed = true;
                    continue;
                }
                if ($result === 'wrote') {
                    $wrote = true;
                }

                $ext = pathinfo($src, PATHINFO_EXTENSION);
                $expectedVariantOutputs[] = variantPath($src, $variant, $ext . '.spv');
                $stage = STAGES[$ext];
                if ($stage['entry'] !== '') {
                    $expectedVariantOutputs[] = variantPath($src, $variant, $ext . '.metal');
                }
            }
        }
    }

    sort($manifestLines);
    $manifestPath = $tree . DIRECTORY_SEPARATOR . 'shaders.manifest';
    if (empty($manifestLines)) {
        if (is_file($manifestPath) && !$tools['check']) {
            unlink($manifestPath);
            $wrote = true;
        } else if ($tools['check'] && is_file($manifestPath) && filesize($manifestPath) > 0) {
            fwrite(STDERR, "shaders: stale {$manifestPath}\n");
            $failed = true;
        }
    } else {
        $manifest = implode("\n", $manifestLines) . "\n";
        $manifestResult = emit($manifestPath, $manifest, $tools['check']);
        if ($manifestResult === 'error') {
            $failed = true;
        } else if ($manifestResult === 'wrote') {
            $wrote = true;
        }
    }

    if (checkStale($tree, $expectedVariantOutputs, $manifestLines) === 'error') {
        $failed = true;
    }

    if ($failed) {
        return 'error';
    }

    return $wrote ? 'wrote' : 'same';
}

function compileStage(
    string $src,
    string $tree,
    array $tools,
    string $variant,
    array $defines,
) : string
{
    // the BAKES dirs sit under resources/shaders, so the default tree walk
    // reaches every stage the bake already built. Compiling it twice yields
    // the same bytes; --check still redoes it, because that pass is what
    // diffs the committed output.
    static $built = [];
    $once = $src . '|' . $variant;

    if (!$tools['check'] && isset($built[$once])) {
        return 'same';
    }

    $built[$once] = true;
    $ext = pathinfo($src, PATHINFO_EXTENSION);
    $stage = STAGES[$ext];
    $rel = relativeTo($src, $tree);
    // std140 and friends are declared in includes, so reflect against the
    // preprocessed text rather than the file on disk
    $text = preprocess($src, $stage['glslang'], $tools, $defines);

    if ($text === null) {
        fwrite(STDERR, "shaders: preprocess failed ({$rel})\n");
        return 'error';
    }

    if ($variant === '') {
        $spvPath = $src . '.spv';
        $metalPath = $src . '.metal';
        $label = $rel;
    } else {
        $spvPath = variantPath($src, $variant, $ext . '.spv');
        $metalPath = variantPath($src, $variant, $ext . '.metal');
        $label = programStem($rel, $ext) . '+' . $variant . '.' . $ext;
    }

    $tmpSpv = $spvPath . '.tmp';
    ensureDir(dirname($tmpSpv));

    $glslangCmd = [
        $tools['glslang'],
        '-V',
        '-S', $stage['glslang'],
        '--target-env', 'vulkan1.2',
        '-P' . PREAMBLE,
        '-I' . dirname($src),
    ];
    foreach ($tools['includes'] as $inc) {
        $glslangCmd[] = '-I' . $inc;
    }
    foreach ($defines as $name => $value) {
        $glslangCmd[] = '-D' . $name . '=' . $value;
    }
    $glslangCmd[] = '-o';
    $glslangCmd[] = $tmpSpv;
    $glslangCmd[] = $src;

    $r = run($glslangCmd);
    if ($r['code'] !== 0) {
        @unlink($tmpSpv);
        fwrite(STDERR, "shaders: glslang failed ({$label})\n{$r['out']}{$r['err']}");
        return 'error';
    }

    if ($tools['spirvVal'] !== null) {
        $r = run([$tools['spirvVal'], $tmpSpv]);
        if ($r['code'] !== 0) {
            @unlink($tmpSpv);
            fwrite(STDERR, "shaders: spirv-val failed ({$label})\n{$r['out']}{$r['err']}");
            return 'error';
        }
    }

    $reflectErr = validateReflection($tmpSpv, $label, $text, $tools['spirvCross']);
    if ($reflectErr !== null) {
        @unlink($tmpSpv);
        fwrite(STDERR, "shaders: {$reflectErr}\n");
        return 'error';
    }

    $spv = file_get_contents($tmpSpv);
    unlink($tmpSpv);

    $changed = emitBytes($spvPath, $spv, $tools['check']);
    if ($changed === 'error') {
        return 'error';
    }

    $metalChanged = 'same';
    if ($stage['entry'] !== '') {
        $tmpMetal = $metalPath . '.tmp';
        $mslCmd = [
            $tools['spirvCross'],
            $spvPath,
            '--msl',
            '--msl-version', '20100',
            '--msl-decoration-binding',
            '--rename-entry-point', 'main', $stage['entry'], $stage['spirv'],
            '--output', $tmpMetal,
        ];
        // --check compares against committed metal; compile from the just-written
        // or existing spv. When check and spv was same, $spvPath exists.
        if ($tools['check'] && $changed === 'same') {
            // use committed spv
        }
        $r = run($mslCmd);
        if ($r['code'] !== 0) {
            @unlink($tmpMetal);
            fwrite(STDERR, "shaders: spirv-cross msl failed ({$label})\n{$r['out']}{$r['err']}");
            return 'error';
        }
        $metal = stamp(shiftMetalBuffers(file_get_contents($tmpMetal)));
        unlink($tmpMetal);
        if ($ext === 'tesse') {
            $metal = str_replace('[[ patch(quad, 0) ]]', '[[patch(quad, 4)]]', $metal);
            $metal = str_replace('[[patch(quad, 0)]]', '[[patch(quad, 4)]]', $metal);
        }
        $metalChanged = emit($metalPath, $metal, $tools['check']);
        if ($metalChanged === 'error') {
            return 'error';
        }
    }

    $targets = '.spv';
    if ($stage['entry'] !== '') {
        $targets = $targets . ' .metal';
    }

    if ($tools['check']) {
        fwrite(STDOUT, "shaders: ok {$label} -> {$targets}\n");
        return 'same';
    }

    fwrite(STDOUT, "shaders: {$label} -> {$targets}\n");

    if ($changed === 'wrote' || $metalChanged === 'wrote') {
        return 'wrote';
    }

    return 'same';
}

/**
 * The fully expanded source glslang will compile. Includes are
 * resolved, so a block declared in an include is visible to the
 * layout checks.
 */
function preprocess(string $src, string $stage, array $tools, array $defines) : ?string
{
    $cmd = [
        $tools['glslang'],
        '-E',
        '-S', $stage,
        '-P' . PREAMBLE,
        '-I' . dirname($src),
    ];
    foreach ($tools['includes'] as $inc) {
        $cmd[] = '-I' . $inc;
    }
    foreach ($defines as $name => $value) {
        $cmd[] = '-D' . $name . '=' . $value;
    }
    $cmd[] = $src;

    $r = run($cmd);
    if (str_contains($r['out'], 'compilation errors') || str_contains($r['err'], 'compilation errors')) {
        fwrite(STDERR, $r['out'] . $r['err']);
        return null;
    }

    return $r['out'];
}

function validateReflection(string $spvPath, string $label, string $src, string $spirvCross) : ?string
{
    $tmpJson = $spvPath . '.json';
    $r = run([$spirvCross, $spvPath, '--reflect', '--output', $tmpJson]);
    if ($r['code'] !== 0) {
        @unlink($tmpJson);
        return "{$label}: spirv-cross --reflect failed\n{$r['out']}{$r['err']}";
    }
    $json = json_decode(file_get_contents($tmpJson), true);
    unlink($tmpJson);

    if (!is_array($json)) {
        return "{$label}: reflection is not JSON";
    }

    foreach ($json['push_constants'] ?? [] as $_) {
        return "{$label}: push constants are not used";
    }

    foreach ($json['ubos'] ?? [] as $ubo) {
        $name = (string) ($ubo['name'] ?? '?');
        $set = (int) ($ubo['set'] ?? -1);
        $binding = (int) ($ubo['binding'] ?? -1);
        if ($set !== 0 || $binding < 0 || $binding >= UNIFORM_SLOTS) {
            return "{$label}: UBO {$name} must be set 0, binding < " . UNIFORM_SLOTS;
        }
        if (!blockIsStd140($src, $name)) {
            return "{$label}: UBO {$name} must be std140";
        }
    }

    foreach ($json['textures'] ?? [] as $tex) {
        $name = (string) ($tex['name'] ?? '?');
        $set = (int) ($tex['set'] ?? -1);
        $binding = (int) ($tex['binding'] ?? -1);
        if ($set !== 1 || $binding < 0 || $binding >= TEXTURE_SLOTS) {
            return "{$label}: sampler {$name} must be set 1, binding < " . TEXTURE_SLOTS;
        }
    }

    foreach ($json['separate_images'] ?? [] as $img) {
        $name = (string) ($img['name'] ?? '?');
        return "{$label}: {$name} is a separate image; use combined sampler2D";
    }

    foreach ($json['separate_samplers'] ?? [] as $samp) {
        $name = (string) ($samp['name'] ?? '?');
        return "{$label}: {$name} is a separate sampler; use combined sampler2D";
    }

    return null;
}

function blockIsStd140(string $src, string $name) : bool
{
    if (preg_match('/layout\s*\(([^)]*)\)\s*uniform\s+' . preg_quote($name, '/') . '\b/', $src, $m) === 1) {
        return str_contains($m[1], 'std140');
    }

    // anonymous block matching the instance name, or the type name after uniform
    if (preg_match('/layout\s*\(([^)]*)\)\s*uniform\s+\w+\s+' . preg_quote($name, '/') . '\b/', $src, $m) === 1) {
        return str_contains($m[1], 'std140');
    }

    return false;
}

function collect(string $dir) : array
{
    $out = [];
    $flags = FilesystemIterator::SKIP_DOTS | FilesystemIterator::CURRENT_AS_FILEINFO;
    $it = new RecursiveIteratorIterator(new RecursiveDirectoryIterator($dir, $flags));

    foreach ($it as $file) {
        if (!$file->isFile()) {
            continue;
        }

        $ext = $file->getExtension();
        if (!isset(STAGES[$ext])) {
            continue;
        }

        $out[] = $file->getPathname();
    }

    sort($out);
    return $out;
}

function groupPrograms(array $sources) : array
{
    $programs = [];

    foreach ($sources as $src) {
        $ext = pathinfo($src, PATHINFO_EXTENSION);
        $stem = programStem($src, $ext);
        $programs[$stem][] = $src;
    }

    ksort($programs);
    return $programs;
}

function programStem(string $path, string $ext) : string
{
    $base = basename($path);
    $suffix = '.' . $ext;
    if (str_ends_with($base, $suffix)) {
        $base = substr($base, 0, -strlen($suffix));
    }
    $dir = dirname($path);
    if ($dir === '.' || $dir === '') {
        return $base;
    }
    // keep only the filename stem for the manifest (scan is a filename walk)
    return $base;
}

function parseVariants(string $text) : array
{
    $out = [];
    if (preg_match_all(VARIANT_PRAGMA, $text, $matches, PREG_SET_ORDER) === false) {
        return $out;
    }

    foreach ($matches as $m) {
        $name = $m[1];
        $defines = [];
        $rest = trim($m[2]);
        if ($rest !== '') {
            foreach (preg_split('/\s+/', $rest) as $token) {
                if ($token === '') {
                    continue;
                }
                $eq = strpos($token, '=');
                if ($eq === false) {
                    $defines[$token] = '1';
                } else {
                    $defines[substr($token, 0, $eq)] = substr($token, $eq + 1);
                }
            }
        }
        $out[$name] = $defines;
    }

    return $out;
}

function unionVariants(array $stages) : array
{
    $variants = [];
    foreach ($stages as $src) {
        foreach (parseVariants(file_get_contents($src)) as $name => $defines) {
            if (isset($variants[$name]) && $variants[$name] !== $defines) {
                fwrite(STDERR, "shaders: variant {$name} define mismatch across stages of " . basename($src) . "\n");
            }
            $variants[$name] = $defines;
        }
    }
    ksort($variants);
    return $variants;
}

function manifestLine(string $stem, string $variant, array $defines) : string
{
    $parts = [$stem . '+' . $variant];
    foreach ($defines as $name => $value) {
        $parts[] = $name . '=' . $value;
    }
    return implode(' ', $parts);
}

function variantPath(string $src, string $variant, string $suffix) : string
{
    $ext = pathinfo($src, PATHINFO_EXTENSION);
    $stem = substr($src, 0, -(strlen($ext) + 1));
    return $stem . '+' . $variant . '.' . $suffix;
}

function checkStale(string $tree, array $expected, array $manifestLines) : string
{
    $ok = true;
    $expectedSet = [];
    foreach ($expected as $path) {
        $expectedSet[$path] = true;
    }

    $manifestNames = [];
    foreach ($manifestLines as $line) {
        $bits = preg_split('/\s+/', $line);
        $manifestNames[$bits[0]] = true;
    }

    $flags = FilesystemIterator::SKIP_DOTS | FilesystemIterator::CURRENT_AS_FILEINFO;
    $it = new RecursiveIteratorIterator(new RecursiveDirectoryIterator($tree, $flags));

    foreach ($it as $file) {
        if (!$file->isFile()) {
            continue;
        }
        $name = $file->getFilename();
        if (preg_match('/^(.+)\+([^.]+)\.(vert|frag|geo|tessc|tesse)\.(spv|metal)$/', $name, $m) !== 1) {
            continue;
        }
        $key = $m[1] . '+' . $m[2];
        if (!isset($manifestNames[$key])) {
            fwrite(STDERR, "shaders: stale variant output {$file->getPathname()}\n");
            $ok = false;
        }
    }

    foreach ($expected as $path) {
        if (!is_file($path)) {
            fwrite(STDERR, "shaders: missing variant output {$path}\n");
            $ok = false;
        }
    }

    return $ok ? 'same' : 'error';
}

/**
 * Compile one library tree and emit its baked Echo file. Every program
 * in the tree, base and variants, lands in one lookup keyed by the
 * program name (`stem` or `stem+variant`).
 */
function bakeTree(string $root, array $spec, array $tools) : string
{
    $dir = $root . DIRECTORY_SEPARATOR . 'resources' . DIRECTORY_SEPARATOR . 'shaders'
        . DIRECTORY_SEPARATOR . $spec['dir'];
    $out = $root . DIRECTORY_SEPARATOR . str_replace('/', DIRECTORY_SEPARATOR, $spec['out']);
    $name = basename($spec['out']);

    if (!is_dir($dir)) {
        fwrite(STDERR, "shaders: bake sources missing under {$dir}\n");
        return 'error';
    }

    $sources = collect($dir);
    if (empty($sources)) {
        fwrite(STDERR, "shaders: no stage files in {$dir}\n");
        return 'error';
    }

    $wasCheck = $tools['check'];
    $tools['check'] = false;
    $programs = [];

    foreach (groupPrograms($sources) as $stem => $stages) {
        $builds = ['' => []] + unionVariants($stages);

        foreach ($builds as $variant => $defines) {
            $program = $variant === '' ? $stem : $stem . '+' . $variant;

            foreach ($stages as $src) {
                $ext = pathinfo($src, PATHINFO_EXTENSION);
                if (STAGES[$ext]['entry'] === '') {
                    fwrite(STDERR, "shaders: bake only handles vert/frag ({$src})\n");
                    return 'error';
                }

                if (compileStage($src, $dir, $tools, $variant, $defines) === 'error') {
                    return 'error';
                }

                if ($variant === '') {
                    $spvPath = $src . '.spv';
                    $metalPath = $src . '.metal';
                } else {
                    $spvPath = variantPath($src, $variant, $ext . '.spv');
                    $metalPath = variantPath($src, $variant, $ext . '.metal');
                }

                $programs[$program][$ext] = [
                    'spv' => file_get_contents($spvPath),
                    'metal' => file_get_contents($metalPath),
                ];
            }
        }
    }

    $tools['check'] = $wasCheck;
    ksort($programs);
    $eco = bakeEcoTree($programs, $spec['ns'], $spec['prefix'], $spec['title']);
    $result = emit($out, $eco, $wasCheck);

    if ($result === 'error') {
        return 'error';
    }

    if ($wasCheck) {
        fwrite(STDOUT, "shaders: ok {$name}\n");
        return 'same';
    }

    fwrite(STDOUT, "shaders: {$name}\n");
    return $result;
}

function bakeEcoTree(array $programs, string $ns, string $prefix, string $title) : string
{
    $metal = bakeArm($programs, $prefix, true);
    $spirv = bakeArm($programs, $prefix, false);
    $names = implode(', ', array_keys($programs));

    return <<<ECO
/**
 * {$title} Programs: {$names}. Generated by
 * `php tools/shaders.php --bake`. Do not edit.
 */

namespace {$ns};

#[if: (os == darwin || os == ios) && !VISU_BACKEND_VULKAN]
{$metal}#[else]
{$spirv}#[end]

ECO;
}

/**
 * One arm of the lookup: MSL source on Darwin/iOS, SPIR-V hex elsewhere.
 */
function bakeArm(array $programs, string $prefix, bool $isMetal) : string
{
    $body = '';

    foreach ($programs as $program => $stages) {
        foreach ($stages as $ext => $bytes) {
            $kind = $ext === 'vert' ? 'vertex' : 'fragment';

            if ($isMetal) {
                $value = echoSingleQuoted($bytes['metal']);
            } else {
                $value = 'visu::graphics::hexBytes(\'' . bin2hex($bytes['spv']) . '\')';
            }

            $body = $body . "    if (\$program == '{$program}' && \$kind == visu::graphics::ShaderKind::{$kind}) {\n"
                . "        return {$value};\n"
                . "    }\n\n";
        }
    }

    return "internal function {$prefix}Bytes(string \$program, visu::graphics::ShaderKind \$kind) : string?\n"
        . "{\n"
        . $body
        . "    return null;\n"
        . "}\n";
}

function echoSingleQuoted(string $s) : string
{
    $s = str_replace(['\\', "'"], ['\\\\', "\\'"], $s);
    return "'" . $s . "'";
}

function emit(string $path, string $contents, bool $check) : string
{
    if ($check) {
        if (!is_file($path)) {
            fwrite(STDERR, "shaders: missing generated file {$path}\n");
            return 'error';
        }

        $have = file_get_contents($path);
        if ($have !== $contents) {
            fwrite(STDERR, "shaders: stale {$path}\n");
            return 'error';
        }

        return 'same';
    }

    if (is_file($path) && file_get_contents($path) === $contents) {
        return 'same';
    }

    ensureDir(dirname($path));
    if (file_put_contents($path, $contents) === false) {
        fwrite(STDERR, "shaders: could not write {$path}\n");
        return 'error';
    }

    return 'wrote';
}

