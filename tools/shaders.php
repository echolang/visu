#!/usr/bin/env php
<?php

/**
 * Compile Vulkan GLSL to desktop GLSL 330 and Metal via SPIR-V.
 *
 *   php tools/shaders.php
 *   php tools/shaders.php examples/shader/shaders
 *   php tools/shaders.php --check
 *
 * Source is `quad.vert` / `quad.frag` (glslang stage files).
 * Outputs are `quad.vert.glsl` + `quad.vert.metal`, which
 * ShaderCollection.scan already loads.
 */

const MARKER = '// generated by tools/shaders.php — do not edit';
const MTL_UNIFORM_BASE = 2;
const PREAMBLE = '#extension GL_GOOGLE_include_directive : enable';

const STAGES = [
    'vert' => ['glslang' => 'vert', 'spirv' => 'vert', 'entry' => 'vs'],
    'frag' => ['glslang' => 'frag', 'spirv' => 'frag', 'entry' => 'fs'],
    'geo' => ['glslang' => 'geom', 'spirv' => 'geom', 'entry' => ''],
    'tessc' => ['glslang' => 'tesc', 'spirv' => 'tesc', 'entry' => ''],
    'tesse' => ['glslang' => 'tese', 'spirv' => 'tese', 'entry' => ''],
];

const DEFAULT_TREES = [
    'examples/shader/shaders',
    'examples/quickstart/resources/shader',
    'tests/resources/shaders',
];

function main(array $argv) : int
{
    $root = dirname(__DIR__);
    $args = array_slice($argv, 1);
    $check = false;
    $dirs = [];

    foreach ($args as $arg) {
        if ($arg === '--check') {
            $check = true;
            continue;
        }

        if ($arg === '--help' || $arg === '-h') {
            fwrite(STDOUT, usage());
            return 0;
        }

        $dirs[] = $arg;
    }

    if (empty($dirs)) {
        foreach (DEFAULT_TREES as $rel) {
            $dirs[] = $root . DIRECTORY_SEPARATOR . $rel;
        }
    }

    $glslang = findBin(['glslangValidator', 'glslang']);
    $spirvCross = findBin(['spirv-cross']);

    if ($glslang === null) {
        fwrite(STDERR, "shaders: glslangValidator not found. brew install glslang\n");
        return 1;
    }

    if ($spirvCross === null) {
        fwrite(STDERR, "shaders: spirv-cross not found. brew install spirv-cross\n");
        return 1;
    }

    $spvRoot = $root . DIRECTORY_SEPARATOR . 'ecobuild' . DIRECTORY_SEPARATOR . 'shaders';
    $failed = 0;
    $wrote = 0;

    foreach ($dirs as $dir) {
        $abs = realpath($dir);

        if ($abs === false || !is_dir($abs)) {
            fwrite(STDERR, "shaders: not a directory: {$dir}\n");
            $failed = $failed + 1;
            continue;
        }

        $sources = collect($abs);

        if (empty($sources)) {
            fwrite(STDOUT, "shaders: no stage files in {$abs}\n");
            continue;
        }

        foreach ($sources as $src) {
            $result = compileOne($src, $abs, $spvRoot, $glslang, $spirvCross, $check);

            if ($result === 'error') {
                $failed = $failed + 1;
                continue;
            }

            if ($result === 'wrote') {
                $wrote = $wrote + 1;
            }
        }
    }

    if ($failed > 0) {
        return 1;
    }

    if ($check) {
        fwrite(STDOUT, "shaders: generated files match\n");
        return 0;
    }

    fwrite(STDOUT, "shaders: wrote {$wrote} program(s)\n");
    return 0;
}

function usage() : string
{
    return <<<TXT
Compile Vulkan GLSL to GLSL 330 and Metal (SPIR-V in between).

  php tools/shaders.php [dir...] [--check]

With no dirs, compiles the example and test shader trees.
--check compiles and diffs against the committed outputs.

TXT;
}

function collect(string $dir) : array
{
    $out = [];
    $flags = FilesystemIterator::SKIP_DOTS | FilesystemIterator::CURRENT_AS_FILEINFO;
    $it = new RecursiveIteratorIterator(new RecursiveDirectoryIterator($dir, $flags));

    foreach ($it as $file) {
        if (!$file->isFile()) {
            continue;
        }

        $ext = $file->getExtension();

        if (!isset(STAGES[$ext])) {
            continue;
        }

        $out[] = $file->getPathname();
    }

    sort($out);
    return $out;
}

function compileOne(
    string $src,
    string $tree,
    string $spvRoot,
    string $glslang,
    string $spirvCross,
    bool $check,
) : string
{
    $ext = pathinfo($src, PATHINFO_EXTENSION);
    $stage = STAGES[$ext];
    $rel = relativeTo($src, $tree);
    $base = $src;

    $spvPath = $spvRoot . DIRECTORY_SEPARATOR . ltrim($rel, DIRECTORY_SEPARATOR) . '.spv';
    $glslPath = $base . '.glsl';
    $metalPath = $base . '.metal';

    ensureDir(dirname($spvPath));

    $glslangCmd = [
        $glslang,
        '-V',
        '-S', $stage['glslang'],
        '--target-env', 'vulkan1.1',
        '-I' . dirname($src),
        '-P' . PREAMBLE,
        '-o', $spvPath,
        $src,
    ];
    $r = run($glslangCmd);

    if ($r['code'] !== 0) {
        fwrite(STDERR, "shaders: glslang failed ({$rel})\n{$r['out']}{$r['err']}");
        return 'error';
    }

    $tmpGlsl = $spvPath . '.glsl.tmp';
    $glslCmd = [
        $spirvCross,
        $spvPath,
        '--version', '330',
        '--no-es',
        '--flatten-ubo',
        '--output', $tmpGlsl,
    ];
    $r = run($glslCmd);

    if ($r['code'] !== 0) {
        fwrite(STDERR, "shaders: spirv-cross glsl failed ({$rel})\n{$r['out']}{$r['err']}");
        return 'error';
    }

    $glsl = stamp(fixGlsl(file_get_contents($tmpGlsl)));
    unlink($tmpGlsl);

    $metal = null;

    if ($stage['entry'] !== '') {
        $tmpMetal = $spvPath . '.metal.tmp';
        $mslCmd = [
            $spirvCross,
            $spvPath,
            '--msl',
            '--msl-version', '20100',
            '--msl-decoration-binding',
            '--rename-entry-point', 'main', $stage['entry'], $stage['spirv'],
            '--output', $tmpMetal,
        ];
        $r = run($mslCmd);

        if ($r['code'] !== 0) {
            fwrite(STDERR, "shaders: spirv-cross msl failed ({$rel})\n{$r['out']}{$r['err']}");
            return 'error';
        }

        $metal = stamp(shiftMetalBuffers(file_get_contents($tmpMetal)));
        unlink($tmpMetal);
    }

    $changed = emit($glslPath, $glsl, $check);

    if ($changed === 'error') {
        return 'error';
    }

    $metalChanged = 'same';

    if ($metal !== null) {
        $metalChanged = emit($metalPath, $metal, $check);

        if ($metalChanged === 'error') {
            return 'error';
        }
    }

    $targets = '.glsl';

    if ($metal !== null) {
        $targets = $targets . ' .metal';
    }

    if ($check) {
        fwrite(STDOUT, "shaders: ok {$rel} -> {$targets}\n");
        return 'same';
    }

    fwrite(STDOUT, "shaders: {$rel} -> {$targets}\n");

    if ($changed === 'wrote' || $metalChanged === 'wrote') {
        return 'wrote';
    }

    return 'same';
}

function emit(string $path, string $contents, bool $check) : string
{
    if ($check) {
        if (!is_file($path)) {
            fwrite(STDERR, "shaders: missing generated file {$path}\n");
            return 'error';
        }

        $have = file_get_contents($path);

        if ($have !== $contents) {
            fwrite(STDERR, "shaders: stale {$path}\n");
            return 'error';
        }

        return 'same';
    }

    if (is_file($path) && file_get_contents($path) === $contents) {
        return 'same';
    }

    if (file_put_contents($path, $contents) === false) {
        fwrite(STDERR, "shaders: could not write {$path}\n");
        return 'error';
    }

    return 'wrote';
}

function stamp(string $source) : string
{
    return MARKER . "\n" . $source;
}

function fixGlsl(string $source) : string
{
    // 330 core + Apple GL-on-Metal: no 420pack, UBOs flattened to vec4 arrays
    $source = str_replace("#version 330\n", "#version 330 core\n", $source);
    $source = preg_replace(
        '/#ifdef GL_ARB_shading_language_420pack\r?\n#extension GL_ARB_shading_language_420pack : require\r?\n#endif\r?\n\r?\n/',
        '',
        $source
    );
    $source = preg_replace('/^(#version 330 core)\n(?!\n)/', "$1\n\n", $source);

    return $source;
}

function shiftMetalBuffers(string $msl) : string
{
    // SPIRV-Cross emits uniform buffers as `constant T& name [[buffer(N)]]`.
    // Vertex / storage buffers keep their SPIR-V index.
    return preg_replace_callback(
        '/constant\b[^;{]*\[\[buffer\((\d+)\)\]\]/',
        function (array $m) : string {
            $n = ((int) $m[1]) + MTL_UNIFORM_BASE;
            return preg_replace('/\[\[buffer\(\d+\)\]\]/', "[[buffer({$n})]]", $m[0], 1);
        },
        $msl
    );
}

function relativeTo(string $path, string $root) : string
{
    $root = rtrim($root, DIRECTORY_SEPARATOR) . DIRECTORY_SEPARATOR;

    if (str_starts_with($path, $root)) {
        return substr($path, strlen($root));
    }

    return basename($path);
}

function ensureDir(string $dir) : void
{
    if (is_dir($dir)) {
        return;
    }

    mkdir($dir, 0777, true);
}

function findBin(array $names) : ?string
{
    $paths = explode(PATH_SEPARATOR, (string) getenv('PATH'));

    foreach ($names as $name) {
        foreach ($paths as $dir) {
            if ($dir === '') {
                continue;
            }

            $candidate = $dir . DIRECTORY_SEPARATOR . $name;

            if (is_file($candidate) && is_executable($candidate)) {
                return $candidate;
            }
        }
    }

    return null;
}

function run(array $cmd) : array
{
    $proc = proc_open($cmd, [
        0 => ['pipe', 'r'],
        1 => ['pipe', 'w'],
        2 => ['pipe', 'w'],
    ], $pipes);

    if (!is_resource($proc)) {
        return ['code' => 1, 'out' => '', 'err' => "could not start {$cmd[0]}\n"];
    }

    fclose($pipes[0]);
    $out = stream_get_contents($pipes[1]);
    $err = stream_get_contents($pipes[2]);
    fclose($pipes[1]);
    fclose($pipes[2]);
    $code = proc_close($proc);

    return ['code' => $code, 'out' => $out, 'err' => $err];
}

exit(main($argv));
